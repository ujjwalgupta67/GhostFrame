from __future__ import annotations

from collections.abc import Callable

from .models import Finding, MisuseScenario
from .normalization import stable_finding_id


def _unique(items: list[Finding]) -> list[Finding]:
    return sorted({item.finding_id: item for item in items}.values(), key=lambda item: item.finding_id)


def _scenario(
    category: str,
    title: str,
    evidence: list[Finding],
    *,
    summary: str,
    possible_misuse: str,
    exposed_asset: str,
    conditions: list[str],
    likelihood: str,
    impact: str,
    confidence: str,
    why: str,
    protection: list[str],
    alternative: str,
    not_proven: str,
    required: list[Finding] | None = None,
    actionability: str = "Review",
) -> MisuseScenario:
    evidence = _unique(evidence)
    ids = [item.finding_id for item in evidence]
    required_ids = [item.finding_id for item in _unique(required or evidence)]
    return MisuseScenario(
        scenario_id=stable_finding_id("SCEN", category, title, "|".join(ids)),
        title=title,
        category=category,
        summary=summary,
        possible_misuse=possible_misuse,
        exposed_asset=exposed_asset,
        required_conditions=conditions,
        likelihood=likelihood,
        impact=impact,
        confidence=confidence,
        evidence_finding_ids=ids,
        required_evidence_ids=required_ids,
        why_it_matters=why,
        recommended_protection=protection,
        alternative_explanation=alternative,
        not_proven=not_proven,
        actionability=actionability,
    )


def _where(findings: list[Finding], predicate: Callable[[Finding], bool]) -> list[Finding]:
    return [item for item in findings if predicate(item)]


def build_misuse_scenarios(findings: list[Finding]) -> list[MisuseScenario]:
    scenarios: list[MisuseScenario] = []
    by_name = {item.field_name.lower(): item for item in findings}

    latitude = by_name.get("gpslatitudedecimal")
    longitude = by_name.get("gpslongitudedecimal")
    if latitude and longitude:
        times = _where(findings, lambda item: item.subcategory == "timeline" and any(key in item.field_name.lower() for key in ("original", "capture", "date", "time")))
        scenarios.append(_scenario(
            "precise_location", "Precise location exposure", [latitude, longitude] + times[:1],
            required=[latitude, longitude], summary="Valid latitude and longitude metadata can disclose where the image was created.",
            possible_misuse="A recipient could use the coordinates for unwanted location inference or connect the photograph to a sensitive place.",
            exposed_asset="Recorded capture location" + (" and time context" if times else ""),
            conditions=["The recipient obtains the original metadata-bearing file.", "Both coordinate values remain valid.", "The metadata describes the relevant location and was not copied or edited."],
            likelihood="Likely", impact="High", confidence="Confirmed",
            why="Coordinates become stronger context when combined with a capture timestamp. Repeated coordinates across several authorized files could reveal a routine, but one file cannot establish one.",
            protection=["Remove GPS metadata before sharing.", "Review visible landmarks and text separately."],
            alternative="The coordinates may be stale, copied, edited, or generated by a device with an inaccurate position.",
            not_proven="This does not prove who captured the image, why anyone was there, or that the location is a home or workplace.",
            actionability="Remove before sharing",
        ))

    identity = _where(findings, lambda item: item.subcategory in {"identity", "comment", "tracked change", "collaboration metadata"} or item.field_name.lower() in {"creator", "author", "artist", "cameraownername", "lastmodifiedby", "manager", "company"})
    if identity:
        scenarios.append(_scenario(
            "identity_disclosure", "Recorded identity disclosure", identity,
            summary="One or more name or organization labels are stored in the file metadata.",
            possible_misuse="The labels could be used to associate a supposedly anonymous file with a recorded identity or make targeted impersonation attempts more believable.",
            exposed_asset="Recorded names and affiliation clues",
            conditions=["The recipient inspects the metadata.", "The recorded label relates to the current file rather than a default, alias, or copied template."],
            likelihood="Possible", impact="High", confidence="High",
            why="Identity-like metadata can undermine an attempt to share a file anonymously.",
            protection=["Clear author, owner, organization, comment, and revision identities.", "Review visible content and the filename for matching clues."],
            alternative="Names may be aliases, outdated values, application defaults, or copied template data.",
            not_proven="The recorded person is not proven to have written, edited, owned, or shared the file.",
            actionability="Remove before sharing" if any(item.sanitizable for item in identity) else "Do not share until resolved",
        ))

    serials = _where(findings, lambda item: "serial" in item.field_name.lower() or "uniqueid" in item.field_name.lower().replace(" ", ""))
    models = _where(findings, lambda item: item.field_name.lower() in {"model", "cameramodel", "lensmodel", "make"})
    if serials:
        scenarios.append(_scenario(
            "device_linking", "Cross-file device linking", serials + models,
            required=serials, summary="A device or lens serial-like identifier can act as a persistent file fingerprint.",
            possible_misuse="Someone comparing several files could link them to the same recorded equipment.", exposed_asset="Device-level correlation identifier",
            conditions=["The identifier is genuine and was not copied or edited.", "Another file exposes the same identifier."],
            likelihood="Likely", impact="High", confidence="High",
            why="A serial-like value is more distinctive than a camera model alone.",
            protection=["Remove serial and unique-device metadata before sharing.", "Re-scan the sanitized copy for equivalent identifiers."],
            alternative="Metadata may be copied between files or altered by editing software.",
            not_proven="A matching identifier does not prove who owns or used the equipment.", actionability="Remove before sharing",
        ))

    timeline = _where(findings, lambda item: item.subcategory == "timeline" or any(key in item.field_name.lower() for key in ("date", "time", "created", "modified", "printed")))
    if timeline:
        scenarios.append(_scenario(
            "timeline_reconstruction", "Timeline reconstruction", timeline,
            summary="The file records one or more capture, creation, editing, printing, comment, or revision times.",
            possible_misuse="The timestamps could reveal parts of a work, publication, collaboration, or travel timeline.", exposed_asset="Recorded activity timeline",
            conditions=["The timestamps have not been changed or copied.", "Missing timezone or clock differences are interpreted correctly."],
            likelihood="Possible", impact="Moderate", confidence="High",
            why="Several timestamps can provide context about when the file moved through a workflow.",
            protection=["Remove nonessential timestamps before sharing.", "Review timezone notes and avoid treating differences as proof of tampering."],
            alternative="Clock errors, timezone differences, exports, copying, and metadata editing can produce inconsistent times.",
            not_proven="Different timestamps do not prove tampering, travel, authorship, or the exact order of real-world events.", actionability="Review",
        ))

    collaboration = _where(findings, lambda item: item.subcategory in {"comment", "tracked change", "collaboration metadata"})
    if collaboration:
        scenarios.append(_scenario(
            "collaboration_leakage", "Collaboration and revision leakage", collaboration,
            summary="Comments, reviewer records, or tracked changes expose collaboration history.",
            possible_misuse="A recipient could recover internal discussion, deleted revision content, reviewer identities, or workflow details.", exposed_asset="Internal review history and draft context",
            conditions=["The recipient uses a viewer or package tool that exposes review data.", "The records were not intentionally included."],
            likelihood="Likely", impact="High", confidence="Confirmed",
            why="Review information often remains stored even when it is not visible in the normal page view.",
            protection=["Remove comments and comment-person data.", "Accept or reject tracked changes appropriately before sharing."],
            alternative="Reviewer names can be aliases or application defaults, and revisions may be intentionally retained.",
            not_proven="A recorded editor is not proven to have personally made every change.", actionability="Remove before sharing",
        ))

    organization = _where(findings, lambda item: item.field_name.lower() in {"company", "manager", "template", "attachedtemplate"} or item.subcategory == "external data configuration")
    if organization:
        scenarios.append(_scenario(
            "organization_profiling", "Organization profiling", organization,
            summary="Organization, manager, template, or workflow fields may connect the file to an environment.",
            possible_misuse="The clues could support organization profiling or make targeted impersonation attempts more believable.", exposed_asset="Organization and workflow context",
            conditions=["The values are current and relate to the file's actual environment.", "The recipient combines them with other information."],
            likelihood="Possible", impact="Moderate", confidence="High",
            why="Affiliation and template clues can reveal more context than a generic filename alone.",
            protection=["Clear company, manager, and template properties.", "Remove external templates and data-source relationships."],
            alternative="Values may come from an old employer, a shared template, or software defaults.",
            not_proven="The metadata does not prove current employment, authorization, or organizational ownership.", actionability="Remove before sharing",
        ))

    software = _where(findings, lambda item: item.subcategory == "software")
    if software:
        scenarios.append(_scenario(
            "software_fingerprinting", "Software environment fingerprinting", software,
            summary="The file records software or producer information.",
            possible_misuse="A recipient could profile the document-production environment or research whether an old recorded version had known issues.", exposed_asset="Recorded editing or export environment",
            conditions=["The value reflects the software actually used rather than an export library or stale template.", "A version value is present if version-specific conclusions are attempted."],
            likelihood="Possible", impact="Low", confidence="High",
            why="Software names provide provenance context, but usually have limited privacy impact alone.",
            protection=["Remove nonessential software metadata if provenance should remain private.", "Keep software patched independently of what metadata records."],
            alternative="The value may identify only an export library, converter, or copied template.",
            not_proven="A recorded version does not prove that version is currently installed. GhostFrame does not perform vulnerability scanning.", actionability="Review",
        ))

    external = _where(findings, lambda item: item.risk_group == "active_external_behavior" and (item.category == "External relationship" or item.field_name in {"URI", "SubmitForm", "ImportData", "GoToR", "MailMergeConfiguration", "attachedTemplate", "image"}))
    if external:
        scenarios.append(_scenario(
            "external_resource_tracking", "External-resource contact or tracking", external,
            summary="The file contains an external relationship or action that a compatible viewer may contact.",
            possible_misuse="A request could reveal that the document was opened, and a form-related action may attempt to transmit entered data.", exposed_asset="Document-open activity or entered form data",
            conditions=["A compatible viewer resolves or activates the external reference.", "Network access is available.", "Viewer security settings permit the action."],
            likelihood="Possible", impact="High", confidence="Confirmed",
            why="External references create a path from local document viewing to another resource.",
            protection=["Remove external templates, images, links, and data-source relationships before sharing.", "Do not activate the target during review."],
            alternative="The target may be a legitimate resource and may never be contacted by the chosen viewer.",
            not_proven="A hyperlink or external relationship is not automatically malicious and GhostFrame did not contact it.", actionability="Remove before sharing",
        ))

    hidden = _where(findings, lambda item: item.risk_group == "hidden_embedded_content" or item.subcategory in {"comment", "tracked change", "hidden text", "hidden value", "hidden structured data", "included content", "preview"})
    if hidden:
        scenarios.append(_scenario(
            "hidden_content_disclosure", "Hidden-content disclosure", hidden,
            summary="Content or data exists outside the normal visible document view.",
            possible_misuse="A recipient could recover draft text, internal notes, variables, thumbnails, attachments, or embedded material the sender assumed was absent.", exposed_asset="Non-visible document content and package data",
            conditions=["The recipient uses a capable viewer or package-inspection tool.", "The hidden or embedded data contains meaningful information."],
            likelihood="Likely", impact="High", confidence="Confirmed",
            why="Not being visible in the ordinary view does not mean content was removed from the file.",
            protection=["Remove supported hidden metadata and embedded content.", "Review hidden text manually and inspect the sanitized document visually."],
            alternative="Some hidden structures are harmless application data or intentionally embedded content.",
            not_proven="Presence alone does not prove the content is sensitive or malicious; embedded payloads were not opened.",
            actionability="Do not share until resolved" if any(not item.sanitizable and item.severity in {"High", "Critical"} for item in hidden) else "Remove before sharing",
        ))

    active = _where(findings, lambda item: item.field_name in {"JavaScript", "Launch", "VBAProject"} or item.category == "Rich media" or "activex" in item.source.lower() or "oleobject" in item.field_name.lower() or (item.subcategory == "active content"))
    if active:
        scenarios.append(_scenario(
            "active_content", "Active content present", active,
            summary="The file contains a script, launch action, macro, ActiveX, OLE, or rich-media indicator.",
            possible_misuse="A capable application may execute or activate behavior when the file is opened or used.", exposed_asset="Viewer behavior and local application context",
            conditions=["A compatible application supports the feature.", "Security settings and user interaction permit activation."],
            likelihood="Possible", impact="Severe", confidence="Confirmed",
            why="Active structures deserve careful review even though presence alone does not establish harmful behavior.",
            protection=["Remove supported active content before sharing.", "If removal is incomplete, re-export from a trusted application and review again."],
            alternative="The active feature may be legitimate, disabled, or never invoked by the viewer.",
            not_proven="Active content present does not mean malware was found. GhostFrame did not execute or classify the content.",
            actionability="Do not share until resolved" if any(not item.sanitizable for item in active) else "Remove before sharing",
        ))

    # One deterministic scenario per category; stable ordering prevents UI/report drift.
    return sorted({item.category: item for item in scenarios}.values(), key=lambda item: item.category)
